const prefixLimit = 4096;
const officialHosts = new Set(['www.sos.texas.gov', 'www.sos.state.tx.us']);
const knownMethods = new Set(['GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'CONNECT', 'TRACE']);

async function readPrefix(body) {
  if (!body) return { text: '', state: 'absent' };
  const reader = body.getReader();
  const decoder = new TextDecoder();
  let text = '';
  let bytes = 0;
  try {
    while (bytes < prefixLimit) {
      const { done, value } = await reader.read();
      if (done) return { text: text + decoder.decode(), state: 'complete' };
      const chunk = value.subarray(0, prefixLimit - bytes);
      bytes += chunk.byteLength;
      text += decoder.decode(chunk, { stream: true });
    }
    return { text: text + decoder.decode(), state: 'capped' };
  } catch {
    return { text, state: 'read_failed' };
  } finally {
    void reader.cancel().catch(() => {});
    reader.releaseLock();
  }
}

export async function describeTexasRegisterFailure(response) {
  const finalUrl = URL.parse(response.url);
  const official = finalUrl?.protocol === 'https:' && officialHosts.has(finalUrl.host);
  const header = (name) => response.headers.get(name) || '';
  const allow = header('allow').toUpperCase().split(',').map((method) => method.trim());
  const { text, state } = await readPrefix(response.body);
  return {
    severity: 'WARNING',
    message: 'texas_register_upstream_failure',
    method: 'GET',
    status: response.status,
    redirected: response.redirected,
    finalHost: official ? finalUrl.hostname : finalUrl ? 'other' : 'unavailable',
    finalPath: official && finalUrl.pathname === '/texreg/sos/index.html' ? 'current_issue'
      : official && finalUrl.pathname.startsWith('/texreg/archive/') ? 'archive_issue' : 'other',
    contentType: header('content-type').split(';', 1)[0].trim().toLowerCase()
      .match(/^(?:text\/(?:html|plain|xml)|application\/(?:xml|json|xhtml\+xml))$/)?.[0] || 'other',
    server: header('server').trim().toLowerCase()
      .match(/^(?:amazons3|cloudfront|cloudflare|envoy|nginx|awselb\/2\.0)$/)?.[0] || 'other',
    allow: [...new Set(allow.filter((method) => knownMethods.has(method)))],
    cloudFrontVia: /(?:^|[.\s])cloudfront\.net(?:[\s,()]|$)|\(CloudFront\)/i.test(header('via')),
    cloudFrontResponseHeader: response.headers.has('x-amz-cf-id'),
    cloudFrontErrorMarker: /the request could not be satisfied|generated by cloudfront/i.test(text),
    s3MethodNotAllowedMarker: /<Code>MethodNotAllowed<\/Code>/i.test(text),
    s3AccessDeniedMarker: /<Code>AccessDenied<\/Code>/i.test(text),
    methodNotAllowedMarker: /method[\s_-]*not[\s_-]*allowed/i.test(text),
    challengeMarker: header('cf-mitigated').trim().toLowerCase() === 'challenge'
      || /enable javascript and cookies|\/cdn-cgi\/challenge-platform\//i.test(text),
    bodyPrefixState: state
  };
}
